-- Additive journal only. No legacy rows, settings, auth or trading state change.
-- Apply explicitly on an isolated branch first; production requires approval.
CREATE TABLE IF NOT EXISTS shared_sessions(
    session_id TEXT PRIMARY KEY, name TEXT UNIQUE NOT NULL,
    created_at TEXT NOT NULL, data_label TEXT NOT NULL,
    archive_sha256 TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS shared_events(
    sequence BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id TEXT NOT NULL REFERENCES shared_sessions(session_id),
    event_id TEXT NOT NULL, at_utc TEXT NOT NULL,
    kind TEXT NOT NULL, payload TEXT NOT NULL,
    UNIQUE(session_id,event_id));
CREATE INDEX IF NOT EXISTS shared_events_session_sequence
    ON shared_events(session_id,sequence);
